-- Pure regression cases; no Roblox instances or native actions are required.
return function(Motion)
    local results,failed={},0
    local function test(name,fn)
        local ok,err=pcall(fn)
        results[#results+1]={name=name,passed=ok,error=not ok and tostring(err) or nil}
        if not ok then failed=failed+1 end
    end
    local function classify(y,vy,air,extras)
        local s={rootY=y,verticalSpeed=vy,floorAirborne=air,turfY=1.63686865568161}
        for k,v in pairs(extras or {}) do s[k]=v end
        return Motion.classify(s)
    end
    test("full-auto DB prediction excludes its reserve and dispatch allowance",function()
        local b=Motion.sprintBudget("DB",100,25,{dbReserve=40,wrReserve=10})
        assert(b.enforced and b.reserve==40 and b.cutoff==43)
        assert(math.abs(b.seconds-2.28)<1e-8 and b.canSprint)
        local endBudget=Motion.sprintBudget("DB",43,25,{dbReserve=40})
        assert(not endBudget.canSprint and endBudget.seconds==0)
    end)
    test("WR final sprint uses its own lower reserved budget",function()
        local b=Motion.sprintBudget("WR",100,25,{dbReserve=40,wrReserve=10})
        assert(b.reserve==10 and b.cutoff==13 and math.abs(b.seconds-3.48)<1e-8)
        assert(not Motion.sprintBudget("WR",12,25,{wrReserve=10}).canSprint)
    end)
    test("manual assistance keeps its existing sprint allowance",function()
        local b=Motion.sprintBudget("DB",100,25,nil)
        assert(not b.enforced and b.reserve==2 and b.cutoff==2 and math.abs(b.seconds-3.92)<1e-8)
    end)
    test("invalid stamina or reserve data cannot produce infinite sprint",function()
        for _,value in ipairs({-1,0,0/0,math.huge}) do
            local b=Motion.sprintBudget("DB",value,25,{dbReserve=40})
            assert(b.seconds==0 and not b.canSprint)
        end
        local b=Motion.sprintBudget("DB",100,25,{dbReserve=math.huge})
        assert(not b.enforced and b.seconds<4)
    end)
    test("recorded slowed sprint cannot predict full speed",function()
        local s=Motion.locomotion(12.15,true,20,27,3)
        assert(math.abs(s.walkSpeed-12.15)<1e-8 and math.abs(s.runSpeed-9)<1e-8)
    end)
    test("slowed walking still predicts the reduced sprint when engaged",function()
        local s=Motion.locomotion(9,false,20,27,3)
        assert(math.abs(s.walkSpeed-12.15)<1e-8 and math.abs(s.runSpeed-9)<1e-8)
    end)
    test("normal walking before sprint engages preserves sprint forecast",function()
        local s=Motion.locomotion(20,false,20,27,3)
        assert(s.walkSpeed==27 and s.runSpeed==20 and s.speedScale==1)
        assert(Motion.locomotion(20,true,20,27,3).walkSpeed==20)
    end)
    test("pending sprint uses observed speed from the first acknowledged request",function()
        local state=Motion.sprintState(nil,10,20,true,20,27)
        local initial=Motion.locomotion(20,true,20,27,3,state)
        assert(initial.walkSpeed==20 and initial.sprintPending and initial.speedScale==1)
        state=Motion.sprintState(state,10.149,20,true,20,27)
        assert(state.pending)
        state=Motion.sprintState(state,10.151,20,true,20,27)
        local pending=Motion.locomotion(20,true,20,27,3,state)
        assert(pending.walkSpeed==20 and pending.runSpeed==20 and pending.speedScale==1)
        assert(pending.sprintPending and pending.sprintPendingAge>=.15)
    end)
    test("repeated snapshots preserve the pending sprint timer",function()
        local state=Motion.sprintState(nil,0,20,true,20,27)
        for _,now in ipairs({.1,.26,.46,.59}) do
            state=Motion.sprintState(state,now,20,true,20,27)
            assert(state.since==0 and state.age==now)
        end
        assert(Motion.locomotion(20,true,20,27,3.92,state).walkSpeed==20)
    end)
    test("native sprint confirmation restores full forecast immediately",function()
        local state=Motion.sprintState({since=0},.69,27,true,20,27)
        assert(state==nil)
        local speed=Motion.locomotion(27,true,20,27,3,state)
        assert(speed.walkSpeed==27 and speed.runSpeed==20 and speed.speedScale==1 and not speed.sprintPending)
    end)
    test("sprint off resets the pending interval for a new request",function()
        local state=Motion.sprintState({since=0},1,20,false,20,27)
        assert(state==nil)
        state=Motion.sprintState(state,2,20,true,20,27)
        assert(state.since==2 and state.pending and state.age==0)
        assert(Motion.locomotion(20,false,20,27,3,{pending=true,age=1}).walkSpeed==27)
    end)
    test("a slow movement penalty remains distinct from a delayed sprint",function()
        local state=Motion.sprintState({since=0},1,12.15,true,20,27)
        assert(state==nil)
        local speed=Motion.locomotion(12.15,true,20,27,3,{pending=true,age=1})
        assert(math.abs(speed.walkSpeed-12.15)<1e-8 and math.abs(speed.runSpeed-9)<1e-8)
        assert(speed.speedScale<1 and not speed.sprintPending)
    end)
    test("stale state cannot cap confirmed speed or invent stamina",function()
        local stale={pending=true,age=1}
        assert(Motion.locomotion(27,true,20,27,3,stale).walkSpeed==27)
        local empty=Motion.locomotion(20,true,20,27,0,stale)
        assert(empty.walkSpeed==20 and not empty.sprintPending)
        for _,bad in ipairs({0/0,math.huge,-1}) do
            assert(Motion.sprintState(nil,1,bad,true,20,27)==nil)
        end
    end)
    test("pending and confirmed transitions refresh only before actions commit",function()
        local normal={speedScale=1,sprintPending=false}
        local pending={speedScale=1,sprintPending=true}
        assert(Motion.shouldRefreshLocomotion(normal,pending,false))
        assert(Motion.shouldRefreshLocomotion(pending,normal,false))
        assert(not Motion.shouldRefreshLocomotion(normal,pending,true))
        assert(not Motion.shouldRefreshLocomotion(pending,normal,true))
        assert(not Motion.shouldRefreshLocomotion(pending,pending,false))
        assert(Motion.shouldRefreshLocomotion(normal,{speedScale=.45},false))
    end)
    test("penalty forecast recovers immediately when normal speed returns",function()
        assert(Motion.locomotion(12.15,true,20,27,3).walkSpeed<20)
        assert(Motion.locomotion(27,true,20,27,3).walkSpeed==27)
        assert(Motion.locomotion(27,true,20,27,0).walkSpeed==20)
    end)
    test("immobile and invalid speed observations stay bounded",function()
        assert(Motion.locomotion(0,true,20,27,3).walkSpeed==0)
        for _,speed in ipairs({0/0,math.huge,-1,33}) do
            assert(Motion.locomotion(speed,true,20,27,3).walkSpeed==27)
        end
    end)
    test("recorded delayed takeoff cannot become another grounded jump",function()
        local m=classify(5.386147499084473,46.06965637207031,false)
        assert(m.valid and m.physicalAirborne and not m.grounded)
        assert(m.ascendingDespiteGround and not m.nativeAirborne and not m.reachAirborne)
        assert(not m.diveModeMatchesMotion)
    end)
    test("recorded rising park position stays physically airborne",function()
        local m=classify(6.119912624359131,42.799652099609375,false)
        assert(not m.grounded and m.ascendingDespiteGround and not m.reachAirborne)
        assert(math.abs(m.groundRootY-4.63686865568161)<0.00001)
    end)
    test("ordinary grounded velocity and floor jitter remain grounded",function()
        for _,sample in ipairs({{4.636868,0},{4.612091,0.605612},{4.537047,-0.774051},{4.70,4.9}}) do
            local m=classify(sample[1],sample[2],false)
            assert(m.grounded and not m.ascendingDespiteGround and m.diveModeMatchesMotion)
        end
    end)
    test("stationary elevated player does not imply takeoff",function()
        local m=classify(15,0,false)
        assert(m.grounded and not m.physicalAirborne and not m.ascendingDespiteGround)
    end)
    test("elevation alone and velocity alone do not infer ascent",function()
        assert(classify(5,5,false).grounded)
        assert(classify(4.70,40,false).grounded)
    end)
    test("descending elevated body is not grounded by a stale floor flag",function()
        local m=classify(8,-20,false)
        assert(not m.grounded and m.fallingDespiteGround and not m.reachAirborne)
        assert(not m.diveModeMatchesMotion)
    end)
    test("native airborne flag preserves native reach and dive mode",function()
        local m=classify(8,-20,true)
        assert(m.physicalAirborne and m.nativeAirborne and m.reachAirborne)
        assert(not m.grounded and m.diveModeMatchesMotion)
    end)
    test("confirmed flight remains airborne through its apex",function()
        local m=classify(10,0,false,{knownAirborne=true})
        assert(m.physicalAirborne and not m.grounded and not m.ascendingDespiteGround)
        assert(not m.reachAirborne and not m.diveModeMatchesMotion)
    end)
    test("landing clears a prior airborne inference at the ground reference",function()
        local m=classify(4.636868,0,false,{knownAirborne=true})
        assert(m.grounded and m.diveModeMatchesMotion)
    end)
    test("trusted elevated standing reference supports local takeoff detection",function()
        assert(classify(12,0,false,{groundRootY=12}).grounded)
        assert(classify(12.3,20,false,{groundRootY=12}).ascendingDespiteGround)
    end)
    test("invalid numbers cannot authorize grounded jumps or matched dive mode",function()
        for _,bad in ipairs({0/0,math.huge,-math.huge}) do
            local m=classify(5,bad,false)
            assert(not m.valid and not m.grounded and not m.diveModeMatchesMotion)
        end
        local m=Motion.classify({rootY=5,verticalSpeed=0})
        assert(not m.valid and not m.grounded)
    end)
    local restricted={physicalAirborne=true,nativeAirborne=false,reachAirborne=false,canDive=false}
    local pursuit={kind="pursue",reachable=false}
    test("recorded DB4508 restored airborne actions refresh restricted pursuit",function()
        local m=classify(9.416988372802734,23.17964744567871,true)
        assert(Motion.shouldRefreshPursuit(pursuit,restricted,m,false))
    end)
    test("ordinary jump dive survives its first native airborne frame",function()
        assert(not Motion.shouldRefreshPursuit({kind="jumpDive",reachable=true},restricted,
            classify(8,30,true),false))
    end)
    test("restored action refresh waits for native airborne confirmation",function()
        assert(not Motion.shouldRefreshPursuit(pursuit,restricted,classify(8,30,false),false))
    end)
    test("pending or active actions block capability refresh",function()
        assert(not Motion.shouldRefreshPursuit(pursuit,restricted,classify(8,30,true),true))
    end)
    test("ordinary grounded pursuit does not use the takeoff recovery path",function()
        assert(not Motion.shouldRefreshPursuit(pursuit,
            {physicalAirborne=false,nativeAirborne=false,canDive=false},classify(8,30,true),false))
    end)
    test("resnapshot after restored capability prevents repeated refresh",function()
        assert(not Motion.shouldRefreshPursuit(pursuit,
            {physicalAirborne=true,nativeAirborne=true,canDive=true},classify(8,30,true),false))
    end)
    return {total=#results,passed=#results-failed,failed=failed,results=results}
end
