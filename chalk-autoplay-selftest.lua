return function(Policy)
    local results,failed={},0
    local function test(name,fn)
        local ok,err=pcall(fn)
        results[#results+1]={name=name,passed=ok,error=not ok and tostring(err) or nil}
        if not ok then failed=failed+1 end
    end
    local config={Queue={Modes={"1v1","2v2","3v3"},Live={
        ["1v1"]=true,["2v2"]=true,["3v3"]=false,Ranked1v1=true,Ranked2v2=true}},
        Ranked={Modes={Ranked1v1="1v1",Ranked2v2="2v2"}}}
    local function fresh(enabled)
        local p=Policy.new(Policy.modes(config),{enabled=enabled,selectedMode="1v1"})
        p:bootstrap("Idle",nil,0)
        return p
    end
    local lobby={phase="Lobby",dataLoaded=true,alive=true,matchServer=false}
    local function join(p)
        assert(p:step(lobby,0)==nil)
        local action=p:step(lobby,2)
        assert(action and action.command=="Join" and action.mode==p.selectedMode)
        return action
    end
    test("catalog keeps unavailable modes visible and includes both ranked queues",function()
        local m=Policy.modes(config)
        assert(#m==5 and m[3].key=="3v3" and not m[3].available)
        assert(m[4].key=="Ranked1v1" and m[5].label=="Ranked 2v2")
    end)
    test("new settings start disabled and unavailable saved mode cannot enable fallback",function()
        assert(not Policy.new(Policy.modes(config)).enabled)
        local p=Policy.new(Policy.modes(config),{enabled=true,selectedMode="3v3"})
        assert(not p.enabled and p.selectedMode=="1v1")
        assert(not p:selectMode("3v3"))
    end)
    test("lobby joins exactly once and waits for acknowledgement",function()
        local p=fresh(true);join(p)
        for t=2.25,11.75,.25 do assert(p:step(lobby,t)==nil) end
        p:observeQueue({Status="Searching",Mode="1v1"},11.8)
        assert(p:step(lobby,50)==nil and p.owned)
    end)
    test("every per-play phase including Result prevents queueing",function()
        for _,phase in ipairs({"Pick","PreSnap","Hike","Live","RAC","Run","Result"}) do
            local p=fresh(true)
            assert(p:step({phase=phase,dataLoaded=true},10)==nil)
            assert(p.queueStatus=="Match" and not p.owned)
        end
    end)
    test("match server and missing player readiness cannot queue",function()
        for _,s in ipairs({{phase="Lobby",dataLoaded=true,matchServer=true},
            {phase="Lobby",dataLoaded=false},{phase="Lobby",dataLoaded=true,testing=true},
            {phase="Lobby",dataLoaded=true,alive=false}}) do
            local p=fresh(true);p:step(s,0);assert(p:step(s,10)==nil)
        end
    end)
    test("end of game rearms only after actual Lobby and native idle bootstrap",function()
        local p=fresh(true);join(p)
        p:observeQueue({Status="Found",Mode="1v1"},3)
        p:step({phase="Result",dataLoaded=true},4)
        assert(p:step(lobby,6)==nil and p.queueStatus=="Unknown")
        p:bootstrap("Idle",nil,6.1)
        assert(p:step(lobby,8).command=="Join")
    end)
    test("a lobby on a match server waits for native return teleport",function()
        local p=fresh(true);p:step({phase="Result",dataLoaded=true},1)
        assert(p:step({phase="Lobby",dataLoaded=true,matchServer=true},3)==nil)
        assert(p.queueStatus=="Leaving")
    end)
    test("existing manual search survives enabling and changing autoplay mode",function()
        local p=Policy.new(Policy.modes(config),{})
        p:bootstrap("Searching","Ranked1v1",0)
        p:setEnabled(true);p:selectMode("2v2")
        assert(p:step(lobby,0)==nil and p:step(lobby,50)==nil)
        assert(not p.owned and p.queueStatus=="Searching")
    end)
    test("turning autoplay off cancels its own accepted search once",function()
        local p=fresh(true);join(p);p:observeQueue({Status="Searching",Mode="1v1"},3)
        p:setEnabled(false)
        assert(p:step(lobby,3.25).command=="Leave")
        assert(p:step(lobby,3.5)==nil)
        p:observeQueue({Status="Idle"},4)
        assert(p:step(lobby,30)==nil and not p.owned)
    end)
    test("off while Join is pending still cancels a later Searching acknowledgement",function()
        local p=fresh(true);join(p);p:setEnabled(false)
        p:observeQueue({Status="Searching",Mode="1v1"},3)
        assert(p:step(lobby,3).command=="Leave")
    end)
    test("off or mode change cancels pending Join immediately before any acknowledgement",function()
        for _,change in ipairs({"off","mode"}) do
            local p=fresh(true);join(p)
            if change=="off" then p:setEnabled(false) else p:selectMode("2v2") end
            assert(p:step(lobby,2.01).command=="Leave")
            p:observeQueue({Status="Searching",Mode="1v1"},2.1)
            assert(p:step(lobby,2.11)==nil and p.pending=="Leave")
            p:observeQueue({Status="Idle"},2.2)
            local nextAction=p:step(lobby,4)
            assert((change=="off" and nextAction==nil)
                or (change=="mode" and nextAction and nextAction.mode=="2v2"))
        end
    end)
    test("mode change waits for cancellation acknowledgement before new join",function()
        local p=fresh(true);join(p);p:observeQueue({Status="Searching",Mode="1v1"},3)
        assert(p:selectMode("Ranked2v2"))
        assert(p:step(lobby,3.5).command=="Leave")
        assert(p:step(lobby,4)==nil)
        p:observeQueue({Status="Idle"},4.5)
        assert(p:step(lobby,5)==nil)
        assert(p:step(lobby,6).mode=="Ranked2v2")
    end)
    test("late search packets do not undo cancellation or spam Leave",function()
        local p=fresh(true);join(p);p:observeQueue({Status="Searching"},3)
        p:selectMode("2v2");assert(p:step(lobby,3.1).command=="Leave")
        for i=1,10 do
            p:observeQueue({Status="Searching",Mode="1v1"},3.1+i*.1)
            assert(p:step(lobby,3.1+i*.1)==nil and p.pending=="Leave")
        end
    end)
    test("Found wins cancellation race and cannot be cancelled",function()
        local p=fresh(true);join(p);p:setEnabled(false)
        assert(p:observeQueue({Status="Found",Mode="1v1"},3))
        assert(p:step(lobby,4)==nil and not p.owned)
    end)
    test("manual native cancel pauses autoplay rather than silently restarting",function()
        local p=fresh(true);join(p);p:observeQueue({Status="Searching"},3)
        p:observeQueue({Status="Idle"},5)
        assert(not p.enabled and p:step(lobby,20)==nil)
    end)
    test("three rejected joins back off and disable instead of flooding",function()
        local p=fresh(true);join(p)
        p:observeQueue({Status="Error",Message="Try again"},3)
        assert(p.failures==1 and p:step(lobby,7)==nil)
        assert(p:step(lobby,8).command=="Join")
        p:observeQueue({Status="Error"},9)
        assert(p:step(lobby,18)==nil and p:step(lobby,19).command=="Join")
        p:observeQueue({Status="Error"},20)
        assert(not p.enabled and p.failures==3 and p:step(lobby,100)==nil)
    end)
    test("missing Join acknowledgement cancels before any retry",function()
        local p=fresh(true);join(p)
        assert(p:step(lobby,12).command=="Leave")
        assert(p.failures==1 and p:step(lobby,17)==nil)
        p:observeQueue({Status="Idle"},18)
        assert(p:step(lobby,20).command=="Join")
    end)
    test("unconfirmed or rejected cancellation pauses instead of rejoining",function()
        for _,failedLeave in ipairs({false,true}) do
            local p=fresh(true);join(p);p:setEnabled(false)
            p:observeQueue({Status="Searching"},3);p:step(lobby,3)
            if failedLeave then p:observeQueue({Status="Error"},4) else p:step(lobby,14) end
            assert(p.queueStatus=="Blocked" and not p.enabled)
            assert(not p:setEnabled(true) and p:step(lobby,100)==nil)
        end
    end)
    test("found alerts work while autoplay off and deduplicate native repeats",function()
        local p=fresh(false)
        assert(p:observeQueue({Status="Found",Mode="Ranked1v1"},1))
        assert(not p:observeQueue({Status="Found",Mode="Ranked1v1"},2))
        p:step({phase="PreSnap",dataLoaded=true},3)
        assert(not p:observeQueue({Status="Found",Mode="Ranked1v1"},4))
        p:step(lobby,5);p:bootstrap("Idle",nil,5)
        assert(p:observeQueue({Status="Found",Mode="Ranked1v1"},6))
    end)
    test("runtime reload preserves owned search without resending Join",function()
        local idle=Policy.new(Policy.modes(config),{})
        idle:restore({queueStatus="Idle"},4)
        assert(idle.pending==nil and idle.requestAt==nil)
        local before=fresh(true);join(before);before:observeQueue({Status="Searching",Mode="1v1"},3)
        local after=Policy.new(Policy.modes(config),{enabled=true,selectedMode="1v1"})
        after:restore(before:status(),4)
        assert(after:step(lobby,4)==nil and after:step(lobby,20)==nil and after.owned)
        after:setEnabled(false);assert(after:step(lobby,21).command=="Leave")
    end)
    return {total=#results,passed=#results-failed,failed=failed,results=results}
end
